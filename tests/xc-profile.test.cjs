const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const ctx={};vm.createContext(ctx);for(const f of ['stats-data.js','daily-analysis-core.js','xc-profile-core.js'])vm.runInContext(fs.readFileSync(f,'utf8'),ctx);
const C=ctx.DailyStats,X=ctx.XCProfile,date='2026-11-24';
const draw=(region,station,date,n)=>({region,station,date,prizes:{db:['00'+n],g6:region==='MB'?['111','222',n]:[],g7:region==='MB'?['91']: [n],g8:['91']}});
const rows=[];for(let i=1;i<=12;i++)rows.push(draw('MB','mienbac',C.shift(date,-7*i),'391'));
rows.push(draw('MN','bentre','2026-11-17','391'),draw('MT','quangnam','2026-11-17','193'));
const opt={date,region:'MB',station:'mienbac'};
assert.equal(X.rankStation(rows,opt).items[0].number,'391');
assert.equal(X.rankStation(rows,opt).items[0].weekdayHits,12);
assert.equal(X.candidates(rows,{...opt,rule:'both'}).length,0);
assert.ok(X.candidates(rows,{...opt,rule:'both',mode:'family'}).some(n=>n.number==='391'));
assert.equal(X.queryHistory(rows,{...opt,query:'91'}).rows[0].hits,24,'two XC slots per board, not DD');
assert.equal(X.queryHistory(rows,{...opt,query:'391'}).rows[0].hits,24);
assert.ok(X.queryHistory(rows,{...opt,query:'9'}).error);
const future=[...rows,draw('MN','bentre',date,'999'),draw('MB','mienbac',date,'999')];
assert.equal(JSON.stringify(X.rankStation(future,opt)),JSON.stringify(X.rankStation(rows,opt)));
assert.equal(X.rankStation(rows,{...opt,date:C.shift(date,1)}).items.length,0,'weekday separation');
assert.equal(X.rankStation(rows,{...opt,station:'other'}).items.length,0,'station separation');
assert.equal(X.candidates(rows,{...opt,windowDays:1}).length,0,'source window');
assert.equal(X.permutations('001').length,3);
assert.equal(X.rankStation([...rows,draw('MN','bentre','2026-11-23','999')],opt).items.some(n=>n.number==='999'),false,'source-only number is not a weekday precedent');
console.log('XC profile passed: station/weekday isolation, XC scope, exact versus permutation, source windows, both regions and future exclusion.');
